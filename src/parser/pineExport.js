// ── Pine Script v5 export ────────────────────────────────────────────────────
//
// Generates syntactically correct Pine v5 for the validated spec. Conditions are
// emitted in their REGIME/state form (e.g. a moving-average cross becomes
// `fast > slow`), which matches how Null's engine actually holds a position —
// enter while the regime is on, exit when it turns off. Anything that genuinely
// can't be represented is emitted as a // comment, never faked.

function indExpr(ind) {
  switch (ind.kind) {
    case "price": return "close";
    case "sma": return `ta.sma(close, ${ind.period})`;
    case "ema": return `ta.ema(close, ${ind.period})`;
    case "rsi": return `ta.rsi(close, ${ind.period})`;
    case "roc": return `ta.roc(close, ${ind.period})`;
    case "macd": return `(ta.ema(close, ${ind.fast || 12}) - ta.ema(close, ${ind.slow || 26}))`;
    case "macdSignal": return `ta.ema(ta.ema(close, ${ind.fast || 12}) - ta.ema(close, ${ind.slow || 26}), ${ind.signal || 9})`;
    case "bbMiddle": return `ta.sma(close, ${ind.period || 20})`;
    case "bbUpper": return `(ta.sma(close, ${ind.period || 20}) + ${ind.mult || 2} * ta.stdev(close, ${ind.period || 20}))`;
    case "bbLower": return `(ta.sma(close, ${ind.period || 20}) - ${ind.mult || 2} * ta.stdev(close, ${ind.period || 20}))`;
    case "atr": return `ta.atr(${ind.period || 14})`;
    default: return "close";
  }
}

// state/regime expression for a condition (or AND/OR group)
function conditionExpr(c, comments) {
  if (Array.isArray(c.all)) return `(${c.all.map((x) => conditionExpr(x, comments)).join(" and ")})`;
  if (Array.isArray(c.any)) return `(${c.any.map((x) => conditionExpr(x, comments)).join(" or ")})`;
  if (c.type === "cross") return `${indExpr(c.fast)} ${c.dir === "above" ? ">" : "<"} ${indExpr(c.slow)}`;
  if (c.type === "threshold") return `${indExpr(c.indicator)} ${c.op} ${c.value}`;
  if (c.type === "breakout") {
    return c.dir === "high"
      ? `close > ta.highest(close[1], ${c.lookback})`
      : `close < ta.lowest(close[1], ${c.lookback})`;
  }
  if (c.type === "volume") return `volume > ${c.mult || 1.5} * ta.sma(volume, ${c.period || 20})`;
  comments.push(`// NOTE: condition "${c.type}" could not be represented and was omitted.`);
  return "false";
}

export function toPineScript(spec) {
  const comments = [];
  const L = [];
  L.push("//@version=5");
  L.push("// ── Generated by Null — VALIDATED strategy export ──");
  L.push("// Conditions are emitted as regimes (enter while true, exit when false),");
  L.push("// matching Null's engine. TradingView fills intrabar, so its numbers may");
  L.push("// differ slightly from Null's close-evaluated stops.");
  L.push(
    `strategy("${(spec.name || "Null Strategy").replace(/"/g, "'")}", overlay=true, ` +
      "default_qty_type=strategy.percent_of_equity, default_qty_value=100, " +
      "commission_type=strategy.commission.percent, commission_value=0.02, slippage=3)",
  );
  L.push("");

  const entryExpr = spec.entry.map((c) => conditionExpr(c, comments)).join(" and ");
  L.push(`longCondition = ${entryExpr}`);

  let exitExpr;
  if (spec.exit && spec.exit.length) {
    exitExpr = spec.exit.map((c) => conditionExpr(c, comments)).join(" or ");
  } else {
    exitExpr = `not (${entryExpr})`; // exit when the entry regime turns off
  }
  L.push(`exitCondition = ${exitExpr}`);
  L.push("");

  L.push("if longCondition");
  L.push('    strategy.entry("Long", strategy.long)');
  if (spec.direction === "long_short") {
    L.push("if exitCondition");
    L.push('    strategy.entry("Short", strategy.short)');
  } else {
    L.push("if exitCondition");
    L.push('    strategy.close("Long")');
  }
  L.push("");

  // fixed stop-loss / take-profit
  if (spec.stopLoss != null || spec.takeProfit != null) {
    L.push("// Fixed protective exits (evaluated on close in Null; TradingView fills intrabar):");
    const parts = ['strategy.exit("SL/TP", "Long"'];
    if (spec.stopLoss != null) parts.push(`stop=strategy.position_avg_price * (1 - ${spec.stopLoss})`);
    if (spec.takeProfit != null) parts.push(`limit=strategy.position_avg_price * (1 + ${spec.takeProfit})`);
    L.push(parts.join(", ") + ")");
    L.push("");
  }

  // trailing stop (long leg)
  const ts = spec.trailingStop;
  if (ts && ts.type === "atr") {
    L.push(`// ATR trailing stop (${ts.mult || 3}× ATR${ts.period || 14}, long leg):`);
    L.push(`atrTrail = ta.atr(${ts.period || 14})`);
    L.push("var float longTrail = na");
    L.push(`longTrail := strategy.position_size > 0 ? math.max(nz(longTrail[1], close - ${ts.mult || 3} * atrTrail), close - ${ts.mult || 3} * atrTrail) : na`);
    L.push('if strategy.position_size > 0 and close <= longTrail');
    L.push('    strategy.close("Long", comment="ATR trail")');
    L.push("");
  } else if (ts && ts.type === "pct") {
    L.push(`// ${(ts.value * 100).toFixed(1)}% trailing stop (long leg):`);
    L.push("var float longPeak = na");
    L.push("longPeak := strategy.position_size > 0 ? math.max(nz(longPeak[1], close), close) : na");
    L.push(`if strategy.position_size > 0 and close <= longPeak * (1 - ${ts.value})`);
    L.push('    strategy.close("Long", comment="trail")');
    L.push("");
  }

  if (comments.length) {
    L.push("// ── Untranslated parts (disclosed, not faked) ──");
    comments.forEach((c) => L.push(c));
  }

  return L.join("\n");
}
